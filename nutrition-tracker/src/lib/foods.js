import { r2 } from './utils.js';

// ערכי המאגר נשמרים ל-100 גרם. מאכל שהוזן לפי יחידה מומר לפי משקל היחידה
const byUnit = (id, cat, name, uname, grams, kcal, p, c, f, fb = 0) => ({
  id, cat, name, uname, serving: grams,
  kcal: r2((kcal * 100) / grams), p: r2((p * 100) / grams), c: r2((c * 100) / grams), f: r2((f * 100) / grams), fb: r2((fb * 100) / grams),
});
const carb = (id, name, kcal, p, c, f, fb, uname, grams, alt) => ({ ...veg(id, name, kcal, p, c, f, fb, uname, grams, alt), cat: 'carb' });
const per100 = (id, cat, name, kcal, p, c, f, fb = 0) => ({ id, cat, name, kcal, p, c, f, fb, serving: 100 });

/* ירק: ערכים ל-100 גרם. יחידה ראשית (uname/serving) ויחידות נוספות (alt) להזנה לפי יחידות */
const veg = (id, name, kcal, p, c, f, fb, uname, grams, alt) => ({
  id, cat: 'veg', name, kcal, p, c, f, fb, serving: grams, uname, ...(alt ? { alt } : {}),
});

